func TestInspectExtSuperblockReportsBoundedGenericMetadata(t *testing.T) {
	image := syntheticGPTImage()
	putExtSuperblock(image, 40, extFixture{
		blockCount:      5,
		freeBlocks:      2,
		blockSizeLog:    0,
		state:           1,
		revision:        1,
		featureIncompat: 0x44,
		featureROCompat: 0x400,
	})
	report, err := InspectExtSuperblock(bytes.NewReader(image), int64(len(image)), 40, 49)
	if err != nil {
		t.Fatal(err)
	}
	if report.Status != ExtStatusCandidate || report.FilesystemFamily != "ext-family" ||
		report.PartitionFirstLBA != 40 || report.PartitionLastLBA != 49 || report.PartitionBytes != 10*logicalSectorBytes ||
		report.BlockSizeBytes != 1024 || report.BlockCount != 5 || report.FilesystemBytes != 5*1024 ||
		report.FreeBlockCount != 2 || report.FeatureIncompat != 0x44 || report.FeatureROCompat != 0x400 ||
		report.SuperblockChecksumStatus != "valid" || !report.CleanUnmount || !report.NeedsJournalRecovery || !report.RawIdentityRedacted ||
		!report.ImageMetadataRead || report.BlockDeviceOpened || report.MutationsPerformed || report.MountPerformed {
		t.Fatalf("unexpected ext superblock report: %+v", report)
	}
	if report.FilesystemIdentityFingerprint == "" {
		t.Fatal("nonzero dynamic-revision filesystem UUID was not fingerprinted")
	}
	encoded, err := json.Marshal(report)
	if err != nil {
		t.Fatal(err)
	}
	for _, secret := range []string{"fixture-ext-uuid", "EXT4_PRIVATE_LABEL", "/dev/sda", "fixture-private-path"} {
		if strings.Contains(string(encoded), secret) {
			t.Fatalf("report leaked %q: %s", secret, encoded)
		}
	}
}

func TestInspectExtSuperblockClassifiesAbsentAndUnsupportedMetadata(t *testing.T) {
	image := syntheticGPTImage()
	report, err := InspectExtSuperblock(bytes.NewReader(image), int64(len(image)), 40, 49)
	if err != nil || report.Status != ExtStatusNotFound || report.FilesystemFamily != "unknown" {
		t.Fatalf("no ext magic: report=%+v err=%v", report, err)
	}

	putExtSuperblock(image, 40, extFixture{blockCount: 5, blockSizeLog: 0, revision: 1})
	for _, test := range []struct {
		name   string
		mutate func([]byte)
		status ExtStatus
	}{
		{
			name: "block count exceeds containing partition",
			mutate: func(sb []byte) {
				binary.LittleEndian.PutUint32(sb[4:8], 6)
			},
			status: ExtStatusDamaged,
		},
		{
			name: "unsupported block size exponent",
			mutate: func(sb []byte) {
				binary.LittleEndian.PutUint32(sb[24:28], 7)
			},
			status: ExtStatusUnsupported,
		},
		{
			name: "unsupported revision",
			mutate: func(sb []byte) {
				binary.LittleEndian.PutUint32(sb[76:80], 2)
			},
			status: ExtStatusUnsupported,
		},
		{
			name: "free block count exceeds total",
			mutate: func(sb []byte) {
				binary.LittleEndian.PutUint32(sb[12:16], 6)
			},
			status: ExtStatusDamaged,
		},
		{
			name: "high block count without 64-bit feature",
			mutate: func(sb []byte) {
				binary.LittleEndian.PutUint32(sb[0x150:0x154], 1)
			},
			status: ExtStatusDamaged,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			fixture := append([]byte(nil), image...)
			sb := fixture[int(40*logicalSectorBytes+1024):int(40*logicalSectorBytes+2048)]
			test.mutate(sb)
			refreshExtSuperblockChecksum(sb)
			report, err := InspectExtSuperblock(bytes.NewReader(fixture), int64(len(fixture)), 40, 49)
			if err != nil || report.Status != test.status {
				t.Fatalf("ext superblock status=%q want %q: report=%+v err=%v", report.Status, test.status, report, err)
			}
		})
	}
}

func TestInspectExtSuperblockVerifiesIndependentE2fsprogsChecksumFixture(t *testing.T) {
	// Fixed UUID/time generated by e2fsprogs mke2fs -t ext4 -O metadata_csum.
	e2fsprogsSuperblock := "AAgAAAAgAAAAAAAArhkAAPUHAAABAAAAAAAAAAAAAAAAIAAAACAAAAAIAAAAAAAAgENtOAAA//9T7wEAAQAAAIBDbTgAAAAAAAAAAAEAAAAAAAAACwAAAAABAAA8AAAAwgIAAGsEAAAAESIzRFVmd4iZqrvM3e7/UEhBTlRPV0QtVEVTVAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA/AAAAAAAAAAAAAAAAAAAAAAAIAAAAAAAAAAAAAACOs56u53JAhYIy461e79lmAQFAAAwAAAAAAAAAgENtOArzAwAEAAAAAAAAAAAAAAACAAAAUAAAAAIAAAAPAAAAUwAAABEAAADvAwAAYwIAAAAAAAAAAAAAAAAAAAAAAAAAABAAAAAAAAAAAAAAAAAAIAAgAAEAAAAAAAAAAAAAAAAAAAAAAAAABAEAAFQAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAABEBgAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAKqgvbQ=="
	metadata, err := base64.StdEncoding.DecodeString(e2fsprogsSuperblock)
	if err != nil || len(metadata) != extSuperblockBytes {
		t.Fatalf("decode e2fsprogs superblock fixture: bytes=%d err=%v", len(metadata), err)
	}
	const imageBytes = 8 * 1024 * 1024
	image := make([]byte, imageBytes)
	copy(image[extSuperblockOffset:extSuperblockOffset+extSuperblockBytes], metadata)
	report, err := InspectExtSuperblock(bytes.NewReader(image), int64(len(image)), 0, imageBytes/logicalSectorBytes-1)
	if err != nil || report.Status != ExtStatusCandidate || report.SuperblockChecksumStatus != "valid" {
		t.Fatalf("independent e2fsprogs metadata checksum failed: report=%+v err=%v", report, err)
	}

	corrupted := append([]byte(nil), image...)
	corrupted[extSuperblockOffset+0x200] ^= 1
	report, err = InspectExtSuperblock(bytes.NewReader(corrupted), int64(len(corrupted)), 0, imageBytes/logicalSectorBytes-1)
	if err != nil || report.Status != ExtStatusDamaged || report.SuperblockChecksumStatus != "invalid" {
		t.Fatalf("corrupted metadata checksum was not rejected: report=%+v err=%v", report, err)
	}

	unsupported := append([]byte(nil), image...)
	unsupported[extSuperblockOffset+0x175] = 2
	report, err = InspectExtSuperblock(bytes.NewReader(unsupported), int64(len(unsupported)), 0, imageBytes/logicalSectorBytes-1)
	if err != nil || report.Status != ExtStatusUnsupported || report.SuperblockChecksumStatus != "unsupported-algorithm" {
		t.Fatalf("unsupported checksum algorithm was not rejected: report=%+v err=%v", report, err)
	}
}

func TestInspectExtSuperblockRejectsInvalidPartitionBounds(t *testing.T) {
	image := syntheticGPTImage()
	for _, test := range []struct {
		name      string
		diskSize  int64
		firstLBA  uint64
		lastLBA   uint64
		wantState ExtStatus
	}{
		{name: "partition shorter than superblock", diskSize: int64(len(image)), firstLBA: 40, lastLBA: 42, wantState: ExtStatusUnsupported},
		{name: "reversed LBA bounds", diskSize: int64(len(image)), firstLBA: 41, lastLBA: 40, wantState: ExtStatusDamaged},
		{name: "partition exceeds image", diskSize: int64(len(image)), firstLBA: 120, lastLBA: 128, wantState: ExtStatusDamaged},
		{name: "unaligned image", diskSize: int64(len(image) - 1), firstLBA: 40, lastLBA: 49, wantState: ExtStatusDamaged},
	} {
		t.Run(test.name, func(t *testing.T) {
			report, err := InspectExtSuperblock(bytes.NewReader(image), test.diskSize, test.firstLBA, test.lastLBA)
			if err != nil || report.Status != test.wantState || report.BlockDeviceOpened || report.MutationsPerformed || report.MountPerformed {
				t.Fatalf("bounds result=%+v err=%v want status %q", report, err, test.wantState)
			}
		})
	}
	if _, err := InspectExtSuperblock(bytes.NewReader(image), -1, 40, 49); err == nil {
		t.Fatal("negative disk size accepted")
	}
}

func TestInspectExtSuperblockCombines64BitCountersWithinLargeSparseImage(t *testing.T) {
	const sectors = uint64(10_000_000_000)
	const firstLBA = uint64(40)
	lastLBA := sectors - 34
	metadata := make([]byte, extSuperblockBytes)
	putExtSuperblockFields(metadata, extFixture{
		blockCount:      3,
		blockCountHigh:  1,
		freeBlocks:      5,
		blockSizeLog:    0,
		state:           1,
		revision:        1,
		featureIncompat: extIncompat64Bit,
	})
	reader := fixedMetadataReader{offset: int64(firstLBA*logicalSectorBytes + extSuperblockOffset), data: metadata}
	imageSize := int64(sectors * logicalSectorBytes)
	report, err := InspectExtSuperblock(reader, imageSize, firstLBA, lastLBA)
	if err != nil {
		t.Fatal(err)
	}
	wantBlocks := uint64(1)<<32 | 3
	if report.Status != ExtStatusCandidate || report.BlockCount != wantBlocks || report.FilesystemBytes != wantBlocks*1024 {
		t.Fatalf("64-bit block counters not parsed safely: %+v", report)
	}
}

func TestInspectExtSuperblockDoesNotCallOrphanOrUnknownStateClean(t *testing.T) {
	for _, test := range []struct {
		name      string
		state     uint16
		wantState string
	}{
		{name: "clean", state: 1, wantState: "clean-unmount-flag-set"},
		{name: "errors win", state: 1 | 2 | 4, wantState: "errors-recorded"},
		{name: "orphan recovery", state: 4, wantState: "orphan-recovery-in-progress"},
		{name: "orphan plus clean bit", state: 1 | 4, wantState: "orphan-recovery-in-progress"},
		{name: "unknown plus clean bit", state: 1 | 0x8000, wantState: "unknown-state-flags"},
	} {
		t.Run(test.name, func(t *testing.T) {
			image := syntheticGPTImage()
			putExtSuperblock(image, 40, extFixture{blockCount: 5, revision: 1, state: test.state,
				featureROCompat: extROCompatMetadataChecksum})
			report, err := InspectExtSuperblock(bytes.NewReader(image), int64(len(image)), 40, 49)
			if err != nil || report.Status != ExtStatusCandidate || report.SuperblockChecksumStatus != "valid" ||
				report.FilesystemState != test.wantState || report.CleanUnmount != (test.state&1 != 0) {
				t.Fatalf("state=%s want=%s status=%s err=%v", report.FilesystemState, test.wantState, report.Status, err)
			}
		})
	}
}

func TestInspectExtSuperblockOrphanIndicatorsAreBoundedAndIndependent(t *testing.T) {
	for _, test := range []struct {
		name        string
		state       uint16
		lastOrphan  uint32
		roCompat    uint32
		incompat    uint32
		wantOrphan  bool
		wantJournal bool
	}{
		{name: "clean", state: 1},
		{name: "recovery state", state: 1 | 4, wantOrphan: true},
		{name: "orphan list", state: 1, lastOrphan: 11, wantOrphan: true},
		{name: "unvalidated list head", state: 1, lastOrphan: ^uint32(0), wantOrphan: true},
		{name: "orphan present", state: 1, roCompat: extROCompatOrphanPresent, wantOrphan: true},
		{name: "journal only", state: 1, incompat: extIncompatRecover, wantJournal: true},
		{name: "both", state: 1, lastOrphan: 11, incompat: extIncompatRecover, wantJournal: true, wantOrphan: true},
	} {
		t.Run(test.name, func(t *testing.T) {
			sb := make([]byte, extSuperblockBytes)
			putExtSuperblockFields(sb, extFixture{blockCount: 5, revision: 1, state: test.state,
				featureROCompat: test.roCompat | extROCompatMetadataChecksum, featureIncompat: test.incompat})
			binary.LittleEndian.PutUint32(sb[0xe8:0xec], test.lastOrphan)
			refreshExtSuperblockChecksum(sb)
			original := append([]byte(nil), sb...)
			reader := fixedMetadataReader{offset: 40*logicalSectorBytes + extSuperblockOffset, data: sb}
			report, err := InspectExtSuperblock(reader, 128*logicalSectorBytes, 40, 49)
			if err != nil || report.Status != ExtStatusCandidate || report.SchemaVersion != 2 ||
				report.SuperblockChecksumStatus != "valid" || report.NeedsOrphanRecovery != test.wantOrphan ||
				report.NeedsJournalRecovery != test.wantJournal || report.BlockDeviceOpened || report.MutationsPerformed || report.MountPerformed {
				t.Fatalf("wrong bounded recovery observation: %+v err=%v", report, err)
			}
			if !bytes.Equal(sb, original) {
				t.Fatal("inspection changed metadata")
			}
			encoded, err := json.Marshal(report)
			if err != nil || !strings.Contains(string(encoded), `"needs_orphan_recovery":`) ||
				strings.Contains(string(encoded), "fixture-ext-uuid") || strings.Contains(string(encoded), "EXT4_PRIVATE_LABEL") {
				t.Fatal("recovery output missing or not redacted", err)
			}
			sb[0xe8] ^= 0x80 // Do not refresh: recovery fields remain checksum-covered.
			report, err = InspectExtSuperblock(reader, 128*logicalSectorBytes, 40, 49)
			if err != nil || report.Status != ExtStatusDamaged || report.SuperblockChecksumStatus != "invalid" ||
				report.NeedsOrphanRecovery || report.CleanUnmount {
				t.Fatal("bad checksum became a recovery or clean observation", err)
			}
		})
	}
}

type extFixture struct {
	blockCount      uint32
	freeBlocks      uint32
	blockSizeLog    uint32
	state           uint16
	revision        uint32
	featureIncompat uint32
	featureROCompat uint32
	blockCountHigh  uint32
	freeBlocksHigh  uint32
}

func putExtSuperblock(image []byte, partitionFirstLBA uint64, fixture extFixture) {
	const superblockBytes = 1024
	start := int(partitionFirstLBA*logicalSectorBytes + 1024)
	putExtSuperblockFields(image[start:start+superblockBytes], fixture)
}

func putExtSuperblockFields(superblock []byte, fixture extFixture) {
	binary.LittleEndian.PutUint32(superblock[0:4], 4)
	binary.LittleEndian.PutUint32(superblock[4:8], fixture.blockCount)
	binary.LittleEndian.PutUint32(superblock[12:16], fixture.freeBlocks)
	binary.LittleEndian.PutUint32(superblock[0x150:0x154], fixture.blockCountHigh)
	binary.LittleEndian.PutUint32(superblock[0x158:0x15c], fixture.freeBlocksHigh)
	if fixture.blockSizeLog == 0 {
		binary.LittleEndian.PutUint32(superblock[20:24], 1)
	}
	binary.LittleEndian.PutUint32(superblock[24:28], fixture.blockSizeLog)
	binary.LittleEndian.PutUint32(superblock[32:36], fixture.blockCount)
	binary.LittleEndian.PutUint32(superblock[40:44], 4)
	binary.LittleEndian.PutUint16(superblock[56:58], 0xef53)
	binary.LittleEndian.PutUint16(superblock[58:60], fixture.state)
	binary.LittleEndian.PutUint32(superblock[76:80], fixture.revision)
	binary.LittleEndian.PutUint32(superblock[92:96], 4)
	binary.LittleEndian.PutUint32(superblock[96:100], fixture.featureIncompat)
	binary.LittleEndian.PutUint32(superblock[100:104], fixture.featureROCompat)
	copy(superblock[104:120], []byte("fixture-ext-uuid!"))
	copy(superblock[120:136], []byte("EXT4_PRIVATE_LABEL"))
	if fixture.featureROCompat&extROCompatMetadataChecksum != 0 {
		superblock[0x175] = extCRC32CChecksumType
		refreshExtSuperblockChecksum(superblock)
	}
}

func refreshExtSuperblockChecksum(superblock []byte) {
	binary.LittleEndian.PutUint32(superblock[extChecksumOffset:extChecksumOffset+4], extSuperblockChecksum(superblock))
}

type fixedMetadataReader struct {
	offset int64
	data   []byte
}

func (reader fixedMetadataReader) ReadAt(buffer []byte, offset int64) (int, error) {
	if offset != reader.offset || len(buffer) != len(reader.data) {
		return 0, errors.New("unexpected metadata read")
	}
	return copy(buffer, reader.data), nil
}
